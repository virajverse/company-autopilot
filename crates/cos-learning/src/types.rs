use chrono::{DateTime, Utc};
use cos_memory::MemoryNamespace;
use serde::{Deserialize, Serialize};
use thiserror::Error;
use uuid::Uuid;

#[derive(Error, Debug, Clone, PartialEq, Eq)]
pub enum LearningError {
    #[error("Constitutional guardrail blocked modification to restricted domain: {0}")]
    ConstitutionalViolation(String),

    #[error("Proposal '{0}' was not found in registry")]
    ProposalNotFound(Uuid),

    #[error("Memory error during proposal application: {0}")]
    MemoryError(String),
}

/// Lifecycle of a learning proposal.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProposalStatus {
    PendingReview,
    Approved,
    Rejected,
    Applied,
}

/// A structured proposal generated by continuous learning to optimize dynamic operational SOPs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LearningProposal {
    pub id: Uuid,
    pub target_namespace: MemoryNamespace,
    pub target_sop_key: String,
    pub rationale: String,
    pub proposed_content: serde_json::Value,
    pub evidence_outcome_ids: Vec<Uuid>,
    pub status: ProposalStatus,
    pub created_at: DateTime<Utc>,
}

impl LearningProposal {
    pub fn new(
        target_namespace: MemoryNamespace,
        target_sop_key: impl Into<String>,
        rationale: impl Into<String>,
        proposed_content: serde_json::Value,
        evidence_outcome_ids: Vec<Uuid>,
    ) -> Result<Self, LearningError> {
        let key = target_sop_key.into();

        // 1. CONSTITUTIONAL GUARDRAIL: Strict Namespace Boundary
        match &target_namespace {
            MemoryNamespace::Client(scope) => {
                return Err(LearningError::ConstitutionalViolation(format!(
                    "Client memory isolation violation: Learning engine cannot mutate client namespace '{}'",
                    scope.0
                )));
            }
            MemoryNamespace::Task(_) => {
                return Err(LearningError::ConstitutionalViolation(
                    "Learning engine cannot target ephemeral task memory; targets must be operational SOPs in Company scope".to_string()
                ));
            }
            MemoryNamespace::Company | MemoryNamespace::AgentWorking(_) => {}
        }

        // 2. CONSTITUTIONAL GUARDRAIL: Protected System & Governance Key Prefixes
        let lower = key.to_lowercase();
        let is_protected = lower.starts_with("system:")
            || lower.starts_with("governance:")
            || lower.starts_with("security:")
            || lower.starts_with("constitution:")
            || lower.eq("bypass_governance_rules")
            || lower.contains("founder_bypass")
            || lower.contains("risk_override");

        if is_protected {
            return Err(LearningError::ConstitutionalViolation(format!(
                "Target key '{}' is part of the protected constitutional boundary and cannot be altered by learning proposals",
                key
            )));
        }

        Ok(Self {
            id: Uuid::now_v7(),
            target_namespace,
            target_sop_key: key,
            rationale: rationale.into(),
            proposed_content,
            evidence_outcome_ids,
            status: ProposalStatus::PendingReview,
            created_at: Utc::now(),
        })
    }
}
